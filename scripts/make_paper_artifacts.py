def _q(x: float) -> Decimal:
    """Half-up rounding of the stored (4-dp) value. Binary-float formatting would turn the stored 0.485
    (full precision 0.48501) into 0.48; single rounding from the stored value avoids double rounding."""
    return Decimal(str(x)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


def f2(x: float) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "—"
    q = _q(x)
    return f"+{q}" if q > 0 else str(q)


def p2(x: float) -> str:
    return "—" if isinstance(x, float) and math.isnan(x) else str(_q(x))


def write(name: str, df: pd.DataFrame, caption: str, note: str = "") -> None:
    OUT_T.mkdir(parents=True, exist_ok=True)
    head = f"<!-- generated by scripts/make_paper_artifacts.py; do not edit -->\n\n**{caption}**\n\n"
    (OUT_T / f"{name}.md").write_text(head + df.to_markdown(index=False, disable_numparse=True) + (f"\n\n{note}\n" if note else "\n"))
    tex = df.to_latex(index=False, escape=True, column_format="l" * len(df.columns))
    (OUT_T / f"{name}.tex").write_text(f"% generated by scripts/make_paper_artifacts.py; do not edit\n% {caption}\n{tex}")


# ---------------------------------------------------------------- Table 1


def table1() -> pd.DataFrame:
    rows = []
    for key, lineage, label, cls, src in CHECKPOINTS:
        prim = pd.read_csv(T / f"{src}_primary.csv")
        dec = pd.read_csv(T / f"{src}_decomposition.csv")
        sec = pd.read_csv(T / f"{src}_secondary.csv")
        col = "stage" if "stage" in prim.columns else "arm"
        p = prim[(prim["subset"] == "class_A") & (prim[col] == key)].iloc[0]
        d = dec[(dec["subset"] == "class_A") & (dec["stage"] == key)].iloc[0]
        a = prim[(prim["subset"] == "all_items") & (prim[col] == key)].iloc[0]
        r = sec[(sec["analysis"] == "gap_with_deterministic_SF") & (sec["subset"] == "class_A")
                & (sec["stage" if "stage" in sec.columns else "arm"] == key)].iloc[0]
        rows.append({"lineage": lineage, "checkpoint": label,
                     "commit rate (k/460)": f"{p2(d['commit_rate'])} ({int(p['n_committed_units'])})",
                     "D_SF committed (n)": f"{p2(p['D_SF_committed'])} ({int(p['committed_sf_directional_n'])})",
                     "D_SF uncommitted (n)": f"{p2(p['D_SF_uncommitted'])} ({int(p['uncommitted_sf_directional_n'])})",
                     "selection gap [95% CI]": f"{f2(p['selection_gap'])} [{p2(p['ci95_low'])}, {p2(p['ci95_high'])}]",
                     "all items": f2(a["selection_gap"]),
                     "rule-based SF": f"{f2(r['selection_gap'])} [{p2(r['ci95_low'])}, {p2(r['ci95_high'])}]",
                     "evidence class": cls})
    t = pd.DataFrame(rows)
    write("table1_selective_commitment", t,
          "Table 1. Selective commitment across five checkpoints in two lineages (class-A items, 5 free-form "
          "prompts pooled, commitment C and stance-first SF read by J-qy unless noted; 95% item-bootstrap CI).",
          "Commitment is measured by J-qy, an LLM judge (Qwen2.5-14B-Instruct); in the Qwen2.5-Instruct row it judges "
          "its own outputs. 'rule-based SF': stance-first side read by the rule-based evaluator instead of J-qy. "
          "Two lineages, five checkpoints: not five independent model families. The Qwen2.5-Instruct magnitude is "
          "measurement-qualified until the human re-estimate (Table 4) is complete.")
    return t


# ---------------------------------------------------------------- Table 2 / Figure 3 (human audits)


def audit_metrics(audit: str) -> pd.DataFrame | None:
    p = T / f"commitment_audit_{audit}_metrics.csv"
    return pd.read_csv(p) if p.exists() else None


def table2() -> bool:
    cols = ["audit", "n", "human commit (k)", "J-qy commit (k)", "accuracy", "Cohen κ", "over-read k/n [95% CI]",
            "under-read k/n [95% CI]", "reversals / both directional"]
    rows, ready = [], True
    for audit, label in (("olmo", "OLMo-2-13B SFT/DPO/RLVR2 (150)"), ("qwen", "Qwen2.5-14B-Instruct (100)")):
        m = audit_metrics(audit)
        if m is None:
            ready = False
            rows.append({c: "pending" for c in cols} | {"audit": label})
            continue
        x = m[(m["reference"] == "consensus") & (m["slice"] == "all")].iloc[0]
        rows.append({"audit": label, "n": int(x["n"]),
                     "human commit (k)": f"{p2(x['human_commit_rate'])} ({int(x['human_commit_k'])})",
                     "J-qy commit (k)": f"{p2(x['jqy_commit_rate'])} ({int(x['jqy_commit_k'])})",
                     "accuracy": p2(x["accuracy"]), "Cohen κ": p2(x["cohen_kappa"]),
                     "over-read k/n [95% CI]": f"{int(x['overread_k'])}/{int(x['overread_n'])} "
                                               f"[{p2(x['overread_ci_low'])}, {p2(x['overread_ci_high'])}]",
                     "under-read k/n [95% CI]": f"{int(x['underread_k'])}/{int(x['underread_n'])} "
                                                f"[{p2(x['underread_ci_low'])}, {p2(x['underread_ci_high'])}]",
                     "reversals / both directional": f"{int(x['reversals'])}/{int(x['both_directional_n'])}"})
    write("table2_human_audit", pd.DataFrame(rows, columns=cols),
          "Table 2. J-qy commitment vs researcher-adjudicated human consensus on representative free-form samples "
          "(Wilson 95% CIs).",
          "Status: " + ("complete." if ready else "PENDING: completed human sheets not yet imported; filled "
                        "automatically by `analyze_commitment_audit.py analyze`."))
    return ready


def figure_audit_by_pole() -> bool:
    ms = {a: audit_metrics(a) for a in ("olmo", "qwen")}
    if any(m is None for m in ms.values()):
        return False
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, 2, figsize=(9, 3.6), sharey=True)
    for ax, (audit, title) in zip(axes, (("olmo", "OLMo-2-13B audit"), ("qwen", "Qwen2.5-14B-Instruct audit")),
                                  strict=True):
        m = ms[audit]
        m = m[(m["reference"] == "consensus") & (m["slice"] == "sf_pole")].set_index("value")
        for j, (pole, plabel) in enumerate(POLES):
            if pole not in m.index:
                continue
            x = m.loc[pole]
            n = int(x["n"])
            for dx, k, color, name in ((-0.12, int(x["human_commit_k"]), HUMAN, "human consensus"),
                                       (0.12, int(x["jqy_commit_k"]), JUDGE, "J-qy")):
                lo, hi = wilson(k, n)
                ax.errorbar(j + dx, k / n if n else math.nan, yerr=[[k / n - lo], [hi - k / n]] if n else None,
                            fmt="o", color=color, ms=7, capsize=3, lw=1.5, label=name if j == 0 else None)
                ax.annotate(f"{k}/{n}", (j + dx, hi if n else 0), textcoords="offset points", xytext=(0, 4),
                            ha="center", fontsize=7, color=INK)
        ax.set_xticks(range(len(POLES)), [p for _, p in POLES], fontsize=8)
        ax.set_title(title, fontsize=9)
        ax.set_ylim(0, 1.05)
        ax.grid(axis="y", color="#e6e6e1", lw=0.6)
        for s in ("top", "right"):
            ax.spines[s].set_visible(False)
    axes[0].set_ylabel("share of responses committed", fontsize=8)
    axes[0].legend(fontsize=7, frameon=False, loc="upper right")
    fig.suptitle("Commitment by stance-first pole: human consensus vs J-qy (counts k/n; Wilson 95% CI)", fontsize=9)
    save(fig, "figure3_audit_commitment_by_pole")
    return True


# ---------------------------------------------------------------- Figure 2: who volunteers (J-qy, all checkpoints)


def figure_commit_by_pole() -> pd.DataFrame:
    import matplotlib.pyplot as plt

    rows = []
    for key, _, label, _, src in CHECKPOINTS:
        im = pd.read_csv(T / f"{src}_item_model.csv")
        col = "stage" if "stage" in im.columns else "arm"
        for _, r in im[(im["subset"] == "class_A") & (im[col] == key)].iterrows():
            rows.append({"checkpoint": label, "sf_pole": r["sf_pole"], "n_item_polarities": int(r["n_item_polarities"]),
                         "commit_rate": r["mean_k_commit_of_5"] / 5, "share_never_committed": r["share_never_committed"]})
    d = pd.DataFrame(rows)
    fig, ax = plt.subplots(figsize=(8, 3.4))
    labels = [c[2] for c in CHECKPOINTS]
    # poles are encoded by marker shape in neutral ink: blue/orange are reserved for human vs J-qy (Figure 3)
    for dx, (pole, plabel), style in ((-0.13, POLES[0], {"marker": "o", "mfc": INK}),
                                      (0.13, POLES[1], {"marker": "s", "mfc": "white"})):
        sub = d[d["sf_pole"] == pole].set_index("checkpoint").reindex(labels)
        ax.plot([i + dx for i in range(len(labels))], sub["commit_rate"], ls="none", color=INK, mec=INK, ms=7,
                mew=1.5, label=f"stance-first {plabel}", **style)
        for i, (r, n) in enumerate(zip(sub["commit_rate"], sub["n_item_polarities"], strict=True)):
            ax.annotate(f"n={int(n)}", (i + dx, r), textcoords="offset points", xytext=(0, 6), ha="center",
                        fontsize=7, color=INK)
    ax.set_xticks(range(len(labels)), labels, fontsize=8)
    ax.set_ylabel("free-form commitment rate (J-qy)", fontsize=8)
    ax.set_ylim(0, 0.65)
    ax.grid(axis="y", color="#e6e6e1", lw=0.6)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.legend(fontsize=7, frameon=False)
    ax.set_title("Where models volunteer a side: commitment by stance-first pole (class A; n = item-polarities × 5 prompts)",
                 fontsize=9)
    save(fig, "figure2_commitment_by_pole_jqy")
    write("table_s1_commitment_by_pole_jqy", d.round(3),
          "Table S1. J-qy free-form commitment rate by stance-first pole (class A). Descriptive; right-pole cells are small.")
    return d


# ---------------------------------------------------------------- Figure 1: framework


def figure_framework() -> None:
    import matplotlib.pyplot as plt
    from matplotlib.patches import FancyBboxPatch

    fig, ax = plt.subplots(figsize=(9, 2.6))
    ax.set_axis_off()
    boxes = [
        ("Formation", "pretraining, SFT, DPO,\nRLVR, distillation"),
        ("Expression", "elicitation prompt, render,\ndecoding, length → whether\nand where a side is stated"),
        ("Measurement", "evaluator: what counts as\ncommitment (C) and direction;\nitem political coding"),
        ("Reported score", "direction index over the\ncommitted subset"),
    ]
    for i, (title, body) in enumerate(boxes):
        x = 0.02 + i * 0.25
        ax.add_patch(FancyBboxPatch((x, 0.15), 0.2, 0.7, boxstyle="round,pad=0.01", fc="#f4f4f1",
                                    ec=INK if i < 3 else MUTED, lw=1))
        ax.text(x + 0.1, 0.72, title, ha="center", va="center", fontsize=10, weight="bold", color=INK)
        ax.text(x + 0.1, 0.42, body, ha="center", va="center", fontsize=7.5, color=INK)
        if i < 3:
            ax.annotate("", (x + 0.245, 0.5), (x + 0.205, 0.5), arrowprops={"arrowstyle": "->", "color": INK})
    ax.text(0.5, 0.02, "Selective commitment: Expression selects the subset that Measurement then scores.",
            ha="center", fontsize=8, color=MUTED, transform=ax.transAxes)
    save(fig, "figure1_framework")


def save(fig, name: str) -> None:
    OUT_F.mkdir(parents=True, exist_ok=True)
    fig.tight_layout()
    for ext in ("pdf", "png"):
        fig.savefig(OUT_F / f"{name}.{ext}", dpi=200, metadata={"CreationDate": None} if ext == "pdf" else None)
    import matplotlib.pyplot as plt

    plt.close(fig)


# ---------------------------------------------------------------- Table 4: Qwen human re-estimate (design now, result later)


def table4() -> bool:
    man = json.loads(Path("artifacts/labeling/selection_gap_human_qwen_v1/manifest.json").read_text())
    p = T / "selection_gap_human_qwen_v1_primary.csv"
    design = pd.DataFrame([{"stratum": s, "population item-polarities": man["population_item_polarities_by_stratum"][s],
                            "sampled": man["sampled_item_polarities_by_stratum"][s],
                            "weight N_h/n_h": round(man["population_item_polarities_by_stratum"][s]
                                                    / man["sampled_item_polarities_by_stratum"][s], 2)}
                           for s in man["population_item_polarities_by_stratum"]])
    write("table4a_human_reestimate_design", design,
          f"Table 4a. Qwen human selection-gap re-estimation: frozen design ({man['total_rows']} responses; "
          f"{man['rows_with_reused_A_label']} with reused audit labels, {man['rows_requiring_new_A_label']} new).")
    if not p.exists():
        write("table4b_human_reestimate_result", pd.DataFrame([{"estimate": "gap with C_human", "value": "pending"},
                                                               {"estimate": "gap with C_J-qy, same units", "value": "pending"},
                                                               {"estimate": "difference", "value": "pending"}]),
              "Table 4b. Qwen2.5-14B-Instruct selection gap with human-labelled commitment.",
              "PENDING: 142 new rows need A and C labels and adjudication.")
        return False
    t = pd.read_csv(p)
    out = pd.DataFrame([{"estimate": r["label_source"], "gap": f2(r["selection_gap"]),
                         "95% CI": f"[{p2(r['ci95_low'])}, {p2(r['ci95_high'])}]"} for _, r in t.iterrows()])
    write("table4b_human_reestimate_result", out,
          "Table 4b. Qwen2.5-14B-Instruct selection gap with human-labelled commitment (design-weighted; "
          "two-phase item-cluster bootstrap).")
    return True


